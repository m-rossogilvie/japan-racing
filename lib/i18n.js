const CIRCUIT = {
  en: { motegi: "Motegi", suzuka: "Suzuka", okayama: "Okayama", sugo: "SUGO", fuji: "Fuji" },
  ja: { motegi: "もてぎ", suzuka: "鈴鹿", okayama: "岡山", sugo: "SUGO", fuji: "富士" },
};

export function makeLocale(lang, strings = {}) {
  const ja = lang === "ja";
  const ui = ja ? UI.ja : UI.en;
  const map = strings || {};
  return {
    lang: ja ? "ja" : "en",
    ja,
    ui,
    t(key, ...args) {
      const value = ui[key] ?? UI.en[key] ?? key;
      return typeof value === "function" ? value(...args) : value;
    },
    tr(value) {
      const text = value == null ? "" : String(value);
      if (!ja || !text) return text;
      return Object.prototype.hasOwnProperty.call(map, text) ? map[text] : text;
    },
    field(key) {
      const id = `field_${key}`;
      if (ui[id]) return ui[id];
      return this.tr(humanize(key));
    },
    circuit(id, fallback) {
      return CIRCUIT[ja ? "ja" : "en"][id] || fallback || id;
    },
    href(path) {
      const clean = path.startsWith("/") ? path : `/${path}`;
      if (!ja) return clean;
      if (clean === "/") return "/ja";
      return `/ja${clean}`;
    },
    sessionLabel(key, index, count) {
      const base = key === "practice" ? "practice" : key === "qualifying" ? "qualifying" : "race";
      if (count > 1) return this.t(`${base}_n`, index + 1);
      return this.t(base);
    },
  };
}
